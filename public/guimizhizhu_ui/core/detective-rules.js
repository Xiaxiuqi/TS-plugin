function dcwBuildTrickPool() {
  const out = [];
  let parent = '';
  DCW_TRICK_RAW.split('\n').forEach(line => {
    line = line.trim();
    if (!line) return;
    if (line[0] === '#') { parent = line.slice(1).trim(); return; }
    const idx = line.indexOf('|');
    if (idx < 0) return;
    const rest = line.slice(idx + 1);
    const idx2 = rest.indexOf('|');
    const n = parseInt(line.slice(0, idx), 10);
    const name = idx2 < 0 ? rest : rest.slice(0, idx2);
    const principle = idx2 < 0 ? '' : rest.slice(idx2 + 1);
    if (n) out.push({ n, name: name.trim(), principle: principle.trim(), parent });
  });
  return out;
}

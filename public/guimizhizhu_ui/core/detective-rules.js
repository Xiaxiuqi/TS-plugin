function dcwDraw(roleCount) {
  const trick = DCW_TRICK_POOL[Math.floor(Math.random() * DCW_TRICK_POOL.length)];
  const caseTypeNo = Math.floor(Math.random() * 11) + 1;
  const motiveNo = Math.floor(Math.random() * 8) + 1;
  const pick = (obj) => { const keys = Object.keys(obj); return keys[Math.floor(Math.random() * keys.length)]; };
  const axes = [];
  for (let i = 0; i < roleCount; i++) {
    axes.push({ A: pick(DCW_AXIS.A), B: pick(DCW_AXIS.B), C: pick(DCW_AXIS.C), D: pick(DCW_AXIS.D) });
  }
  return {
    trick: { no: trick.n, name: trick.name, principle: trick.principle, parent: trick.parent },
    caseType: { no: caseTypeNo, name: DCW_CASETYPE[caseTypeNo].name, harm: DCW_CASETYPE[caseTypeNo].harm },
    motive: { no: motiveNo, name: DCW_MOTIVE[motiveNo] },
    roleCount, axes,
  };
}
